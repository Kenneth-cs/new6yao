// MARK: - 文章模型
struct Article: Identifiable {
    let id: Int
    let title: String
    let subtitle: String
    let category: ArticleCategory
    let readTime: Int  // 阅读时间（分钟）
    let content: String
    let keyPoints: [String]  // 关键要点
    let actionItems: [String]  // 行动建议
    let relatedArticles: [Int]  // 相关文章ID
    let publishDate: Date
    
    var formattedReadTime: String {
        "\(readTime)分钟阅读"
    }
}

// MARK: - 文章数据源
class ArticleDataSource {
    static let shared = ArticleDataSource()
    
    private init() {}
    
    // 所有文章
    lazy var allArticles: [Article] = [
        // 周易文化（7篇）
        article1_yijingNotSuperstition,
        article2_yinYangThinking,
        article3_baguaSymbols,
        article4_liuyaoStructure,
        article5_changePhilosophy,
        article6_yijingManagement,
        article7_yijingPsychology,
        
        // 决策方法（8篇）
        article8_structuredThinking,
        article9_swotAnalysis,
        article10_multiDimensional,
        article11_riskAssessment,
        article12_timingChoice,
        article13_longTermism,
        article14_intuitionReason,
        article15_decisionReview
        
        // 个人成长（5篇）- 暂时隐藏
        // article16_selfAwareness,
        // article17_goalSetting,
        // article18_actionPower,
        // article19_emotionManagement,
        // article20_continuousLearning
    ]
    
    // 按类别获取文章
    func articles(for category: ArticleCategory) -> [Article] {
        allArticles.filter { $0.category == category }
    }
    
    // 根据ID获取文章
    func article(by id: Int) -> Article? {
        allArticles.first { $0.id == id }
    }
    
    // 搜索文章
    func search(query: String) -> [Article] {
        guard !query.isEmpty else { return allArticles }
        return allArticles.filter { article in
            article.title.localizedCaseInsensitiveContains(query) ||
            article.subtitle.localizedCaseInsensitiveContains(query) ||
            article.content.localizedCaseInsensitiveContains(query)
        }
    }
    
    // 推荐文章
    func recommendedArticles(excluding excludeId: Int? = nil, limit: Int = 3) -> [Article] {
        var articles = allArticles
        if let excludeId = excludeId {
            articles = articles.filter { $0.id != excludeId }
        }
        return Array(articles.shuffled().prefix(limit))
    }
}

