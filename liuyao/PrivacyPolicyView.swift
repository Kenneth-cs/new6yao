import SwiftUI

struct PrivacyPolicyDetailView: View {
    @Environment(\.presentationMode) var presentationMode
    let type: PolicyType
    
    enum PolicyType {
        case privacy
        case terms
        
        var title: String {
            switch self {
            case .privacy: return "隐私政策"
            case .terms: return "用户协议"
            }
        }
        
        var content: String {
            switch self {
            case .privacy: return privacyPolicyText
            case .terms: return userAgreementText
            }
        }
    }
    
    var body: some View {
        NavigationView {
            ScrollView {
                VStack(alignment: .leading, spacing: 16) {
                    Text(type.content)
                        .font(.body)
                        .foregroundColor(.primary)
                        .lineSpacing(8)
                }
                .padding()
            }
            .navigationTitle(type.title)
            .navigationBarTitleDisplayMode(.inline)
            .navigationBarItems(trailing: Button("关闭") {
                presentationMode.wrappedValue.dismiss()
            })
        }
    }
}

